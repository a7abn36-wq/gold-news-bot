cd "$(dirname "$0")"

# منع الموبايل ينوم التيرموكس (مهم عشان البوت يفضل شغال)
termux-wake-lock 2>/dev/null

while true; do
    python bot.py
    echo ""
    echo "⚠️ البوت وقع... هيعيد التشغيل لوحده بعد 5 ثواني (Ctrl+C للإيقاف النهائي)"
    sleep 5
done
